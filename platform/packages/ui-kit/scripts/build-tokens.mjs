// Builds the kit's tokens with Style Dictionary from the three token files in
// tokens/ (W3C design tokens format): common.tokens.json (both kits),
// shell.tokens.json (Aerie, the shell kit) and app.tokens.json (Quill, the
// app kit). Those files are the only place tokens are edited (ADR 0015); the
// CSS custom properties and the typed token map are generated from them.
import StyleDictionary from 'style-dictionary';
import { mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const header = 'Generated by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit.';

// A token's CSS name is its own name, whatever group it sits in: `color.slate` is `--slate`.
const name = (token) => token.path.at(-1);

// The typed map keeps a reference as `{name}`, as the kit's code expects.
const raw = (token) => String(token.original.$value).replace(/\{(?:[a-z0-9-]+\.)*([a-z0-9-]+)\}/g, '{$1}');

const sd = new StyleDictionary({
  source: [join(root, 'tokens/*.tokens.json')],
  usesDtcg: true,
  log: { verbosity: 'silent' },
  hooks: {
    transforms: { 'name/own': { type: 'name', transform: name } },
    fileHeaders: { augur: () => [header] },
    formats: {
      'typescript/token-map': ({ dictionary }) => {
        const map = Object.fromEntries(dictionary.allTokens.map((t) => [t.name, raw(t)]));
        return `// ${header}\nexport const tokens = ${JSON.stringify(map, null, 2)} as const;\n\nexport type TokenName = keyof typeof tokens;\n\n/** A CSS var() reference to a token, for use in component styles. */\nexport const token = (name: TokenName): string => \`var(--\${name})\`;\n`;
      },
    },
  },
  platforms: {
    css: {
      transforms: ['name/own'],
      buildPath: `${join(root, 'dist')}/`,
      files: [{ destination: 'tokens.css', format: 'css/variables', options: { outputReferences: true, fileHeader: 'augur' } }],
    },
    ts: {
      transforms: ['name/own'],
      buildPath: `${join(root, 'src/generated')}/`,
      files: [{ destination: 'tokens.ts', format: 'typescript/token-map' }],
    },
  },
});

mkdirSync(join(root, 'dist'), { recursive: true });
await sd.buildAllPlatforms();
const count = (await sd.getPlatformTokens('css')).allTokens.length;
console.log(`ui-kit: wrote ${count} tokens`);
