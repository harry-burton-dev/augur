// Writes src/generated/ from the API contracts (ADR 0055): for each contracts/<service>.openapi.yaml,
// its types with openapi-typescript (src/generated/<service>.ts), and one index naming every service,
// its path prefix and its client factory. Nothing here is committed: build, typecheck and test run it
// first, so a client is always the contract it was built from. Change the service, not the client.
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const here = fileURLToPath(new URL('..', import.meta.url));
const contracts = join(here, '../../../contracts');
const out = join(here, 'src/generated');
const SUFFIX = '.openapi.yaml';

const HEADER = '// Generated by scripts/generate.mjs from contracts/. Change the service, not this file.\n';

/** events → events, data-atlas → dataAtlas: the name a service's factory starts with. */
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const services = readdirSync(contracts)
  .filter((f) => f.endsWith(SUFFIX))
  .map((f) => f.slice(0, -SUFFIX.length))
  .sort();
if (!services.length) throw new Error(`No ${SUFFIX} files in ${contracts}`);

mkdirSync(out, { recursive: true });

// Turbo runs build, typecheck and test at once, each generating first: a file is replaced whole
// (written beside it, then renamed), and only when it changed, so one never reads another's half-write.
const write = (name, text) => {
  const file = join(out, name);
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  const temp = `${file}.${process.pid}.tmp`;
  writeFileSync(temp, text);
  renameSync(temp, file);
};

const entries = [];
for (const service of services) {
  const file = join(contracts, `${service}${SUFFIX}`);
  const doc = parse(readFileSync(file, 'utf8'));
  // Paths in a contract are relative to its server, whose path is the API's major (/v1).
  const prefix = doc.servers?.[0]?.url ?? `/v${String(doc.info?.version ?? '1').split('.')[0]}`;
  const ast = await openapiTS(pathToFileURL(file));
  write(`${service}.ts`, HEADER + astToString(ast));
  entries.push({ service, name: camel(service), title: doc.info?.title ?? service, version: doc.info?.version ?? '', prefix });
}

const index = [
  HEADER,
  "import { serviceClient, type ServiceClientOptions } from '../client.js';",
  ...entries.map(({ service, name }) => `import type * as ${name}Api from './${service}.js';`),
  '',
  ...entries.map(({ service, name }) => `export type * as ${name} from './${service}.js';`),
  '',
  '/** Each service with a contract: its title, its API version and the path its routes are under. */',
  'export const services = {',
  ...entries.map(({ service, title, version, prefix }) => `  ${JSON.stringify(service)}: { title: ${JSON.stringify(title)}, version: ${JSON.stringify(version)}, prefix: ${JSON.stringify(prefix)} },`),
  '} as const;',
  '',
  ...entries.flatMap(({ service, name, title, version, prefix }) => [
    `/** A typed client for the ${title} API (${version}), at \`/api/${service}${prefix}\` behind the gateway unless \`baseUrl\` or \`gateway\` says otherwise. */`,
    `export const ${name}Client = (options?: ServiceClientOptions) => serviceClient<${name}Api.paths>(${JSON.stringify(service)}, services[${JSON.stringify(service)}].prefix, options);`,
    '',
  ]),
].join('\n');
write('index.ts', index);
// A contract that's gone takes its client with it.
const keep = new Set(['index.ts', ...services.map((s) => `${s}.ts`)]);
for (const f of readdirSync(out)) if (!keep.has(f) && !f.endsWith('.tmp')) rmSync(join(out, f));
console.log(`Generated clients for ${services.join(', ')}`);
