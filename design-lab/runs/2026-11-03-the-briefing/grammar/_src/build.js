/* Builds ../vN-*.html from vN-*.tpl.html: inlines common.css, the DATA object and common.js.
   Run: node build.js */
const fs = require('fs'), path = require('path');
const here = __dirname;
const DATA = require('./data.js');
const css = fs.readFileSync(path.join(here, 'common.css'), 'utf8');
const js = fs.readFileSync(path.join(here, 'common.js'), 'utf8');
const head = `/* ======================================================================
   Sample data for one deployment (${DATA.org}). Every name, label, count,
   sentence and word on this sheet comes from here; in AUGUR it would come
   from Data Atlas (records, grades, empties), Artifacts and Mandate.
   Generated by _src/build.js from _src/data.js (fixed seed).
   ====================================================================== */
const DATA = ${JSON.stringify(DATA)};
`;
for (const f of fs.readdirSync(here).filter(f => f.endsWith('.tpl.html'))) {
  const out = fs.readFileSync(path.join(here, f), 'utf8')
    .replace('/*@COMMON_CSS*/', () => css)
    .replace('/*@DATA*/', () => head + '\n' + js);
  fs.writeFileSync(path.join(here, '..', f.replace('.tpl', '')), out);
  console.log('built', f.replace('.tpl', ''));
}
