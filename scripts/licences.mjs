#!/usr/bin/env node
// AUGUR is proprietary (LICENSE, docs/licensing.md). This keeps it so, and credits what others wrote.
//
//   node scripts/licences.mjs check     in CI: every package.json says UNLICENSED, no production
//                                       dependency is under a strong or network copyleft licence (or an
//                                       unknown one) without a reviewed entry in licences.allow.json, and
//                                       every image the Compose file runs, other than AUGUR's own, is
//                                       credited in licences.extra.json
//   node scripts/licences.mjs notices   writes THIRD_PARTY_NOTICES.md from the installed production
//                                       dependencies (pnpm licenses) and licences.extra.json. Run by
//                                       version-packages, so every release ships current notices, and by
//                                       the Lockfile workflow
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const NOTICES = 'THIRD_PARTY_NOTICES.md';
const COMPOSE = 'infra/deploy/compose.yml';
/** AUGUR's own packages: the workspace's, the kit's from GitHub Packages, and the apps'. Not credited. */
const OWN = /^@(augur|apps)\/|^@harry-burton-dev\//;
/** Strong and network copyleft: taking one into code AUGUR ships could force AUGUR's own code open. */
const REFUSED = /^(A?GPL|SSPL|EUPL|OSL)-/;
/** What a package says when it names no licence anyone else may use. */
const UNKNOWN = /^(unknown|unlicensed|none|see licen[cs]e in\b.*)?$/i;

/** One licence identifier, without a `WITH` exception or a trailing `+`. */
const base = (id) => id.replace(/\s+WITH\s+.*$/i, '').replace(/\+$/, '').trim();

/**
 * Whether an SPDX expression may ship: `A OR B` when any branch may, `A AND B` when every part may.
 * Parentheses are read as grouping only (the expressions npm packages use are never deeper).
 */
export function allowed(expression, licenceAllowed = (id) => !REFUSED.test(id) && !UNKNOWN.test(id)) {
  const flat = String(expression ?? '').replace(/[()]/g, ' ').trim();
  if (UNKNOWN.test(flat)) return false;
  return flat.split(/\s+OR\s+/i).some((branch) => branch.split(/\s+AND\s+/i).every((id) => licenceAllowed(base(id))));
}

/** Production dependencies whose licence may not ship, less those a reviewed allow entry covers. */
export function refused(byLicence, allow = []) {
  const out = [];
  for (const [licence, packages] of Object.entries(byLicence)) {
    for (const p of packages) {
      if (OWN.test(p.name) || allowed(p.license ?? licence)) continue;
      if (allow.some((a) => a.package === p.name && a.licence === (p.license ?? licence))) continue;
      out.push(`${p.name}@${p.versions.join(', ')} is under ${p.license ?? licence}`);
    }
  }
  return out.sort();
}

/** The images a Compose file runs that AUGUR doesn't build and licences.extra.json doesn't credit. */
export function uncreditedImages(compose, extra) {
  const credited = new Set((extra.images ?? []).map((i) => i.image));
  const images = [...compose.matchAll(/^\s*image:\s*["']?([^\s"']+)/gm)].map((m) => m[1]).filter((i) => !i.includes('${PLATFORM_IMAGES'));
  return [...new Set(images.map((i) => i.replace(/@sha256:.*$/, '').replace(/:[^/:]+$/, '')))].filter((i) => !credited.has(i)).sort();
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

/** A package's own licence file, if it ships one. */
export function licenceText(dir) {
  if (!dir || !existsSync(dir)) return null;
  const file = readdirSync(dir).sort().find((f) => /^(licen[cs]e|copying)([.-].*)?$/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').replace(/\r\n?/g, '\n').trim() : null;
}

/**
 * THIRD_PARTY_NOTICES.md, the same bytes for the same input: what AUGUR ships (one table per licence),
 * what it runs beside its own code, the data it carries, then each distinct licence text once.
 */
export function renderNotices(byLicence, extra, readText = (p) => licenceText(p.paths?.[0])) {
  const shipped = Object.values(byLicence).flat().filter((p) => !OWN.test(p.name));
  const tables = new Map();
  for (const p of shipped) {
    const licence = p.license || 'Unknown';
    if (!tables.has(licence)) tables.set(licence, []);
    tables.get(licence).push(p);
  }
  const out = [
    '# Third-party notices',
    '',
    'AUGUR is proprietary (see `LICENSE`). It ships and runs open-source parts that others wrote, and each keeps its own licence, listed here.',
    'This file is generated by `pnpm notices` from the installed production dependencies and `licences.extra.json`: change those, not this file.',
    '',
    '## Shipped in AUGUR\'s images and frontends',
  ];
  for (const licence of [...tables.keys()].sort()) {
    out.push('', `### ${licence}`, '', '| Package | Version | Homepage |', '| --- | --- | --- |');
    for (const p of tables.get(licence).sort(byName)) out.push(`| ${cell(p.name)} | ${cell(p.versions.join(', '))} | ${cell(p.homepage)} |`);
  }
  out.push('', '## Run beside AUGUR, unmodified', '', 'Images AUGUR\'s Compose file starts but doesn\'t build. Each is its own program, under its own licence.', '', '| Image | Licence | Homepage | Note |', '| --- | --- | --- | --- |');
  for (const i of [...(extra.images ?? [])].sort((a, b) => (a.image < b.image ? -1 : 1))) out.push(`| ${cell(i.image)} | ${cell(i.licence)} | ${cell(i.homepage)} | ${cell(i.note)} |`);
  out.push('', '## Data', '');
  if (!(extra.data ?? []).length) out.push('AUGUR carries no third-party data files.');
  for (const d of extra.data ?? []) out.push(`- **${d.name}** (\`${d.path}\`): ${d.licence}. ${d.copyright ?? ''} Source: ${d.source}${d.commit ? ` at ${d.commit}` : ''}.`.replace(/\s+\./g, '.'));

  const texts = new Map();
  for (const p of shipped) {
    const text = readText(p);
    if (!text) continue;
    if (!texts.has(text)) texts.set(text, []);
    texts.get(text).push(`${p.name}@${p.versions.join(', ')}`);
  }
  out.push('', '## Licence texts', '', 'Each package\'s own licence file, once for every package that ships the same text.');
  const groups = [...texts.entries()].map(([text, names]) => ({ text, names: names.sort() })).sort((a, b) => (a.names[0] < b.names[0] ? -1 : 1));
  for (const g of groups) out.push('', `### ${g.names.join(', ')}`, '', '```text', g.text.replace(/```/g, "'''"), '```');
  return `${out.join('\n')}\n`;
}

const readJson = (file, fallback) => (existsSync(join(root, file)) ? JSON.parse(readFileSync(join(root, file), 'utf8')) : fallback);

function installed() {
  const json = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return json.trim() ? JSON.parse(json) : {};
}

async function main() {
  const mode = process.argv[2];
  const extra = readJson('licences.extra.json', { images: [], data: [] });
  if (mode === 'notices') {
    writeFileSync(join(root, NOTICES), renderNotices(installed(), extra));
    console.log(`Wrote ${NOTICES}.`);
    return;
  }
  if (mode !== 'check') {
    console.error('Usage: node scripts/licences.mjs check|notices');
    process.exit(2);
  }
  const problems = [];
  const files = execFileSync('git', ['ls-files', 'package.json', '*/package.json'], { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean);
  for (const f of files) {
    if (JSON.parse(readFileSync(join(root, f), 'utf8')).license !== 'UNLICENSED') problems.push(`${f} needs "license": "UNLICENSED" (docs/licensing.md).`);
  }
  for (const r of refused(installed(), readJson('licences.allow.json', { allow: [] }).allow)) {
    problems.push(`${r}: a strong copyleft or unknown licence can't ship in AUGUR without Harry's review (an entry in licences.allow.json, docs/licensing.md), or use another package.`);
  }
  for (const i of uncreditedImages(readFileSync(join(root, COMPOSE), 'utf8'), extra)) {
    problems.push(`${COMPOSE} runs ${i}, which licences.extra.json doesn't credit: add it with its licence.`);
  }
  if (!existsSync(join(root, NOTICES))) problems.push(`${NOTICES} is missing: run pnpm notices.`);
  if (problems.length) {
    for (const p of problems) console.error(`✗ ${p}`);
    process.exit(1);
  }
  console.log('Licences check passed: every package is marked UNLICENSED, no production dependency is under a refused licence, and every image AUGUR runs is credited.');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
